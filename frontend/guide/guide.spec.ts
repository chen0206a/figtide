import { test, expect } from "../e2e/workspace-test";
import { artifactPath } from "../e2e/artifacts";
import fs from "node:fs";
const { version } = JSON.parse(fs.readFileSync("package.json", "utf8"));

test("capture the user guide from the packaged app using only the built-in sample", async ({ page, request }, info) => {
  expect(process.env.LABFLOW_PACKAGE_APP).toBeTruthy();
  expect(process.env.LABFLOW_CAPTURE).toBe("1");
  const connection = await (await request.get("/api/agent/connection")).json();
  expect(connection.model).toBe("labflow-fixture");
  expect(connection.base_url).toContain(`127.0.0.1:${process.env.LABFLOW_FIXTURE_PORT}`);
  const projects = await (await request.get("/api/projects")).json();
  for (const project of projects.filter((p: any) => !p.archived)) {
    expect((await request.put(`/api/projects/${project.id}`, { data: { name: project.name, description: project.description, archived: true } })).ok()).toBe(true);
  }
  const shot = async (name: string) => {
    const notice = page.getByRole("button", { name: "关闭消息", exact: true });
    if (await notice.isVisible()) await notice.click();
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({ path: artifactPath(info, `../docs/guide/${name}.png`), fullPage: true, animations: "disabled" });
  };
  await page.goto("/");
  await expect(page.getByRole("button", { name: "载入示例项目", exact: true })).toBeVisible();
  await shot("01-first-open");
  await page.getByRole("button", { name: "载入示例项目", exact: true }).click();
  await expect(page).toHaveURL(/\/projects\/\d+\/figures\/\d+$/);
  const editor = new URL(page.url()).pathname;
  const projectId = Number(editor.match(/projects\/(\d+)/)![1]);
  await expect(page.locator(".canvas-stage")).toHaveAttribute("aria-busy", "false");
  await shot("03-editor");
  await page.getByRole("link", { name: "项目概览", exact: true }).click();
  await expect(page.getByRole("heading", { name: "学习曲线 · 均值与标准误", exact: true })).toBeVisible();
  await shot("02-sample-home");
  await page.getByRole("button", { name: "关于 FigTide", exact: true }).click();
  await expect(page.getByText(`版本 ${version}`, { exact: true })).toBeVisible();
  await shot("00-version");
  await page.getByRole("dialog").getByRole("button", { name: "关闭", exact: true }).click();
  const csv = fs.readFileSync("src/assets/sample/示例-学习曲线.csv", "utf8").split("\n").filter(line => !line.startsWith("#")).join("\n").trim();
  await page.getByTestId("file-upload").setInputFiles({ name: "示例-学习曲线.csv", mimeType: "text/csv", buffer: Buffer.from(csv) });
  await expect(page.getByLabel("epoch 角色")).toBeVisible();
  await page.getByLabel("epoch 角色").selectOption("x");
  await page.getByLabel("accuracy 角色").selectOption("y");
  await page.getByLabel("model 角色").selectOption("group");
  await shot("04-import");
  await page.getByRole("button", { name: "确认导入", exact: true }).click();
  await expect(page.getByRole("heading", { name: "示例-学习曲线.csv", exact: true })).toBeVisible();
  await shot("05-data");
  await page.goto(editor);
  await expect(page.locator(".canvas-stage")).toHaveAttribute("aria-busy", "false");
  await page.getByRole("button", { name: "外观", exact: true }).click();
  await shot("06-style");
  await page.getByLabel("字体", { exact: true }).selectOption("Noto Sans SC");
  await page.locator(".chart-picker > summary").click();
  await page.getByRole("group", { name: "画布论文尺寸", exact: true }).getByRole("button", { name: "单栏 · 88 mm", exact: true }).click();
  await shot("07-paper-size");
  await page.locator(".chart-picker > summary").click();
  await page.getByRole("button", { name: "导出", exact: true }).click();
  await page.getByLabel("文件格式", { exact: true }).selectOption("pdf");
  await shot("08-export");
  for (const format of ["pdf", "svg", "png"]) {
    if (!(await page.getByLabel("文件格式", { exact: true }).isVisible())) await page.getByRole("button", { name: "导出", exact: true }).click();
    await page.getByLabel("文件格式", { exact: true }).selectOption(format);
    const downloaded = page.waitForEvent("download");
    await page.getByRole("button", { name: "下载图表", exact: true }).click();
    const file = info.outputPath(`sample.${format}`); await (await downloaded).saveAs(file);
    expect(fs.statSync(file).size).toBeGreaterThan(100);
  }
  await page.keyboard.press("Escape");
  await page.locator(".masthead").getByRole("button", { name: "模型设置", exact: true }).click();
  const settings = page.getByRole("dialog", { name: "模型设置", exact: true });
  await settings.getByRole("checkbox").check();
  await settings.getByRole("button", { name: "测试连接", exact: true }).click();
  await expect(settings.getByText("对话与工具调用均正常", { exact: true })).toBeVisible();
  await shot("09-model-settings");
  await settings.getByRole("button", { name: "关闭", exact: true }).click();
  await page.getByRole("button", { name: "绘图助手", exact: true }).click();
  const assistant = page.getByRole("complementary", { name: "绘图助手", exact: true });
  await assistant.getByRole("textbox", { name: "希望怎样调整？" }).fill("续改隐藏网格，让 Y 轴更简洁");
  await assistant.getByRole("checkbox").check();
  await assistant.getByRole("button", { name: "生成调整提案", exact: true }).click();
  await expect(assistant.getByText("提案已就绪", { exact: true })).toBeVisible();
  await expect(page.getByTestId("canvas-proposal")).toBeVisible();
  await shot("10-assistant-proposal");
  await assistant.getByRole("button", { name: "应用这组调整", exact: true }).click();
  await expect(assistant.getByText("已接受", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "撤销", exact: true }).click();
  await expect(page.getByTestId("plot").locator(".gtitle")).toHaveText("Grouped means ± SEM");
  await assistant.getByRole("button", { name: "收起绘图助手", exact: true }).click();
  await page.getByRole("button", { name: "保存", exact: true }).click();
  await expect(page.getByText("已保存 v2", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "管理项目", exact: true }).click();
  await page.getByLabel("备份项目", { exact: true }).selectOption(String(projectId));
  const backup = page.waitForEvent("download");
  await page.getByRole("button", { name: "下载项目备份", exact: true }).click();
  const archive = info.outputPath("sample.labflow.zip"); await (await backup).saveAs(archive);
  await page.getByLabel("选择项目备份", { exact: true }).setInputFiles(archive);
  await expect(page.getByLabel("恢复项目名称", { exact: true })).toBeVisible();
  await page.getByLabel("恢复项目名称", { exact: true }).fill("示例 · 学习曲线 · 恢复");
  await shot("11-backup");
  const all = await (await request.get("/api/projects")).json();
  expect(all.filter((p: any) => !p.archived).every((p: any) => p.name.startsWith("示例 ·"))).toBe(true);
});

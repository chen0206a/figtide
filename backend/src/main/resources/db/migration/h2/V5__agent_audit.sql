-- H2 版：对应 MySQL 的 V5__agent_audit.sql。改动：trace_json、proposal_json JSON→CLOB。内联 INDEX（含 DESC 索引列）实测 H2 2.3.232 支持，原样保留在 CREATE TABLE 里。
CREATE TABLE agent_runs (
  run_id CHAR(36) PRIMARY KEY,
  project_id BIGINT NOT NULL,
  instance_id CHAR(36) NOT NULL,
  chart_id BIGINT NULL,
  base_revision INT NOT NULL,
  dataset_version_id BIGINT NOT NULL,
  source_sha256 CHAR(64) NOT NULL,
  snapshot_hash CHAR(64) NOT NULL,
  model VARCHAR(200) NOT NULL,
  endpoint VARCHAR(512) NOT NULL,
  prompt_version VARCHAR(64) NOT NULL,
  catalog_hash CHAR(64) NOT NULL,
  status VARCHAR(20) NOT NULL,
  outcome VARCHAR(20) NOT NULL,
  reason_code VARCHAR(64) NOT NULL DEFAULT '',
  max_steps INT NOT NULL,
  max_tokens INT NOT NULL,
  timeout_seconds INT NOT NULL,
  steps INT NOT NULL DEFAULT 0,
  prompt_tokens BIGINT NOT NULL DEFAULT 0,
  completion_tokens BIGINT NOT NULL DEFAULT 0,
  tokens BIGINT NOT NULL DEFAULT 0,
  budget_used BIGINT NOT NULL DEFAULT 0,
  usage_complete BOOLEAN NOT NULL DEFAULT FALSE,
  latency_ms BIGINT NOT NULL DEFAULT 0,
  trace_json CLOB NOT NULL,
  proposal_json CLOB NULL,
  proposal_hash CHAR(64) NULL,
  decision_reason VARCHAR(500) NOT NULL DEFAULT '',
  created_at TIMESTAMP(3) NOT NULL,
  finished_at TIMESTAMP(3) NULL,
  decision_at TIMESTAMP(3) NULL,
  INDEX agent_project_created (project_id, created_at DESC, run_id),
  INDEX agent_project_chart (project_id, chart_id, created_at DESC),
  FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);
